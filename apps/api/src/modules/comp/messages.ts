/** Calendar days (en: 2026-10-31, de: 31.10.2026) and the decimal separator per locale. */
const FORMAT_TAGS: Readonly<Record<Locale, string>> = { en: 'en-CA', de: 'de-DE' }

/** Text helpers of one locale: catalogue lookup, market-zone calendar days and decimal strings with the locale's separator. */
export interface Texts {
  readonly t: (key: string, params?: MessageParams) => string
  readonly day: (at: Date, timeZone: string) => string
  /** A decimal string ("12.5", "-0.03") with the locale's decimal separator, no grouping, by string replacement. */
  readonly decimal: (text: string) => string
}

export function textsFor(locale: Pick<PortalLocale, 'locale' | 'defaultLocale'>, log: FastifyBaseLogger): Texts {
  const tag = FORMAT_TAGS[locale.locale]
  const separator = new Intl.NumberFormat(tag).formatToParts(0.5).find((part) => part.type === 'decimal')!.value
  return {
    t: (key, params = {}) => message(COMP_MESSAGES, key, params, locale.locale, locale.defaultLocale, log),
    day: (at, timeZone) => new Intl.DateTimeFormat(tag, { timeZone, year: 'numeric', month: '2-digit', day: '2-digit' }).format(at),
    decimal: (text) => text.replace('.', separator),
  }
}
